// TestFactoryGeminiIdentityMapping asserts the audited identity split: the
// gemini row (registry/gemini.js) dispatches to the native Gemini executor and
// the gemini-cli row (registry/gemini-cli.js, executors/gemini-cli.js) stays on
// the Gemini CLI executor. Both rows share executor_path specialized/gemini,
// so identity is the discriminator.
func TestFactoryGeminiIdentityMapping(t *testing.T) {
	f := registry.NewFactory(nil)

	gemini, ok := f.GetExecutor(provider.ProviderGemini, engine.FormatGemini)
	if !ok {
		t.Fatal("factory: no executor for ProviderGemini")
	}
	if gemini.ProviderType() != provider.ProviderGemini {
		t.Errorf("gemini executor identity = %q, want %q", gemini.ProviderType(), provider.ProviderGemini)
	}

	cli, ok := f.GetExecutor(provider.ProviderGeminiCli, engine.FormatGemini)
	if !ok {
		t.Fatal("factory: no executor for ProviderGeminiCli")
	}
	if cli.ProviderType() != provider.ProviderGeminiCli {
		t.Errorf("gemini-cli executor identity = %q, want %q", cli.ProviderType(), provider.ProviderGeminiCli)
	}

	if gemini.ProviderType() == cli.ProviderType() {
		t.Error("gemini and gemini-cli must map to distinct executors")
	}
}
